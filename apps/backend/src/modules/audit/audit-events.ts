export type AuditAction = (typeof AUDIT_ACTION)[keyof typeof AUDIT_ACTION];

export interface AuditEventInput {
  readonly action: AuditAction;
  readonly actorUserId: string | null;
  readonly targetType: AuditTargetType;
  readonly targetId: string;
  readonly clinicId?: string | null;
  /** Non-sensitive change details (old/new status, role, reason). Never secrets or medical data. */
  readonly metadata?: Readonly<Record<string, unknown>>;
}

/** Append-only writer for privileged changes. Pass the transaction performing the change. */
export class AuditLog {
  async record(executor: SqlExecutor, event: AuditEventInput, meta: RequestMeta): Promise<void> {
    await executor.execute(
      `INSERT INTO audit_events (action, actor_user_id, target_type, target_id, clinic_id, request_id, metadata)
       VALUES (?, ?, ?, ?, ?, ?, ?)`,
      [
        event.action,
        event.actorUserId,
        event.targetType,
        event.targetId,
        event.clinicId ?? null,
        meta.requestId,
        event.metadata === undefined ? null : JSON.stringify(event.metadata),
      ],
    );
  }
}
